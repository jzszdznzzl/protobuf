import type { FileModel } from '../model/types.ts';
import type { CodegenOptions } from '../options.ts';
import { generateClass } from './class-generator.ts';
import { CodeWriter } from './code-writer.ts';
import { generateEnum } from './enum-generator.ts';
import { generateExtension } from './extension-generator.ts';
import { ImportManager } from './import-manager.ts';
import { generateInit } from './interface-generator.ts';
import { outputBaseName } from './paths.ts';
import { generateService } from './service-generator.ts';
import { TypeMapper } from './type-mapper.ts';

export interface GeneratedFile {
  /** Path relative to the output folder, always separated by `/`. */
  path: string;
  content: string;
}

const GENERATOR_NAME = '@jzszdznzzl/protobuf';

/**
 * Registers the message in the JSON type registry, which `google.protobuf.Any` uses to turn a
 * packed message into JSON and back.
 */
function generateRegistration(writer: CodeWriter, tsName: string, imports: ImportManager): void {
  const J = imports.runtime('Json');
  const Reader = imports.runtime('Reader');
  writer.block(
    `${J}.registerType({`,
    () => {
      writer.line(`typeName: ${tsName}.typeName,`);
      writer.line(
        `toJson: (bytes, options) => ${tsName}.read(new ${Reader}(bytes)).toJSON(options),`,
      );
      writer.line(
        `fromJson: (json, options) => ${tsName}.encode(${tsName}.readJSON(json, options)).finish(),`,
      );
    },
    '});',
  );
  writer.line();
}

/**
 * Generates the `.ts` file for a .proto. Every declaration is a top-level export: the package
 * does not become a namespace and nested types are flattened as `Outer_Inner`. Order: enums,
 * then for each message its init type, class and JSON registration, then extensions and services.
 */
export function generateFile(file: FileModel, options: CodegenOptions): GeneratedFile {
  const imports = new ImportManager(file, options);
  const types = new TypeMapper(imports);
  const body = new CodeWriter();
  const services = options.shouldGenerateServices ? file.services : [];

  for (const enumModel of file.enums) {
    generateEnum(body, enumModel, options);
  }
  for (const message of file.messages) {
    generateInit(body, message, types, options);
    generateClass(body, message, types, imports, options);
    if (options.shouldGenerateJson) {
      generateRegistration(body, message.tsName, imports);
    }
  }
  for (const extension of file.extensions) {
    generateExtension(body, extension, types, imports, options);
  }
  for (const service of services) {
    generateService(body, service, imports, options);
  }

  const header = new CodeWriter();
  header.line(`// Code generated by ${GENERATOR_NAME}. DO NOT EDIT.`);
  header.line(
    `// Source: ${file.fileName} (${file.ast.edition ? `edition ${file.ast.edition}` : file.syntax})`,
  );
  header.line('/* eslint-disable */');
  const importLines = imports.render();
  if (importLines.length > 0) {
    header.line();
    for (const line of importLines) {
      header.line(line);
    }
  }

  const hasExports =
    file.enums.length + file.messages.length + file.extensions.length + services.length > 0;
  // A file without imports or exports would not be an ES module.
  const footer = importLines.length > 0 || hasExports ? '' : 'export {};\n';
  return {
    path: `${outputBaseName(file.fileName, options)}.ts`,
    content: `${header.toString()}\n${body.toString()}${footer}`,
  };
}
